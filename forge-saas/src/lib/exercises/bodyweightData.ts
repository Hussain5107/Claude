import type { DayTemplate, ExerciseTemplate } from "./types";

// A full 6-day Push/Pull/Legs split using nothing but bodyweight — for
// training at home without dumbbells, or outdoors in a park. A sturdy
// bench/step/chair is used for two exercises (very common in parks); every
// other movement needs zero equipment. Day numbers/names/subtitles match the
// gym program exactly so per-user day rotation and the dashboard UI work
// unchanged.

function ex(
  overrides: Partial<ExerciseTemplate> &
    Pick<ExerciseTemplate, "slug" | "name" | "equip" | "primary" | "baseSets" | "baseReps" | "baseRest" | "cues" | "mistakes" | "alt" | "tip">,
): ExerciseTemplate {
  return {
    secondary: [],
    baseRpe: "RPE 7–8",
    tempo: "2-1-2",
    difficulty: "beginner",
    breathing: "Exhale on exertion (the lift), inhale on the lowering phase.",
    // Every photo is named after its slug, so the path is derived rather than
    // repeated on each entry. An explicit `image` in overrides still wins.
    image: `/images/${overrides.slug}.jpg`,
    videoUrl: null,
    ...overrides,
  };
}

